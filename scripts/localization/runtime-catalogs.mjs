import { readFileSync } from "node:fs";
import path from "node:path";

/** Review metadata is checked during authoring and is not needed by players. */
export function runtimeCatalog(catalog) {
  return Object.fromEntries(
    Object.entries(catalog).map(([id, entry]) => {
      if (!entry || entry.reviewed !== true || !Object.hasOwn(entry, "source"))
        throw new Error(`Unreviewed runtime localization: ${id}`);
      if (typeof entry.text === "string") return [id, { source: entry.source, text: entry.text }];
      if (entry.forms && typeof entry.forms === "object")
        return [id, { source: entry.source, forms: entry.forms }];
      throw new Error(`Invalid runtime localization: ${id}`);
    }),
  );
}

/** Resolve only generated runtime imports, leaving authoring and test catalogs intact. */
export function runtimeCatalogPlugin() {
  const prefix = "\0fauna-runtime-catalog:";
  const suffix = ".runtime.js";
  return {
    name: "fauna-runtime-catalog",
    enforce: "pre",
    resolveId(source, importer) {
      if (!/^\.\/locales\/[a-z]{2}(?:-[A-Za-z]{2,4})?\.json\?fauna-runtime$/.test(source)) return null;
      if (!importer || path.basename(importer) !== "shipped-catalogs.ts")
        throw new Error("Runtime catalogs must be imported by the generated catalog owner");
      return (
        prefix + path.resolve(path.dirname(importer), source.slice(0, -"?fauna-runtime".length)) + suffix
      );
    },
    load(id) {
      if (!id.startsWith(prefix)) return null;
      const file = id.slice(prefix.length, -suffix.length);
      this.addWatchFile(file);
      return `export default ${JSON.stringify(runtimeCatalog(JSON.parse(readFileSync(file, "utf8"))))};`;
    },
  };
}

/** Production includes only qualified catalogs; development can preview candidates. */
export function runtimeCatalogModule(languages) {
  const qualified = Object.entries(languages)
    .filter(([locale, data]) => locale !== "en" && data.qualified === true)
    .map(([locale]) => locale);
  for (const locale of qualified)
    if (!/^[a-z]{2}(?:-[A-Za-z]{2,4})?$/.test(locale)) throw new Error(`Invalid locale: ${locale}`);
  const imports = qualified.map(
    (locale, index) => `import locale${index} from "./locales/${locale}.json?fauna-runtime";`,
  );
  const entries = qualified.map((locale, index) => `  ["${locale}"]: locale${index},`);
  return [
    "// Generated by npm run localization:extract; production ships qualified catalogs only.",
    'import type { GameLocale } from "./languages";',
    'import type { MessageCatalog } from "./messages";',
    ...imports,
    "",
    ...(entries.length
      ? ["export const shippedCatalogs: Partial<Record<GameLocale, MessageCatalog>> = {", ...entries, "};"]
      : ["export const shippedCatalogs: Partial<Record<GameLocale, MessageCatalog>> = {};"]),
    "",
  ].join("\n");
}
