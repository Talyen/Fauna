/** Production includes only qualified catalogs; development can preview candidates. */
export function runtimeCatalogModule(languages) {
  const qualified = Object.entries(languages)
    .filter(([locale, data]) => locale !== "en" && data.qualified === true)
    .map(([locale]) => locale);
  for (const locale of qualified)
    if (!/^[a-z]{2}(?:-[A-Za-z]{2,4})?$/.test(locale)) throw new Error(`Invalid locale: ${locale}`);
  const imports = qualified.map((locale, index) => `import locale${index} from "./locales/${locale}.json";`);
  const entries = qualified.map((locale, index) => `  ["${locale}"]: locale${index},`);
  return [
    "// Generated by npm run localization:extract; production ships qualified catalogs only.",
    'import type { GameLocale } from "./languages";',
    'import type { MessageCatalog } from "./messages";',
    ...imports,
    "",
    ...(entries.length
      ? ["export const shippedCatalogs: Partial<Record<GameLocale, MessageCatalog>> = {", ...entries, "};"]
      : ["export const shippedCatalogs: Partial<Record<GameLocale, MessageCatalog>> = {};"]),
    "",
  ].join("\n");
}
